#this is to remove all bonded pairs
for k in 1:size(topology.bondIndList,1)
        id1 = Int64(topology.bondIndList[k,1])
        id2 = Int64(topology.bondIndList[k,2])
        eligible[id1,id2] = false
        eligible[id2,id1] = false
end


